#!/usr/bin/env node
/**
 * Data build tool.
 *
 *   node scripts/data/build.mjs split [monolithDir]   cut the monolithic JSON (units.json, unitStats.json, buildings.json,
 *                                                     buildingVisuals.json, heroes.json, engineConfig.json) into the per-race layout
 *                                                     under src/data/ and regenerate src/data/dataFiles.generated.js.
 *                                                     monolithDir defaults to src/data (units.json in src/data/visuals/).
 *                                                     Use it to import a JSON exported from a lab (units.json exports).
 *   node scripts/data/build.mjs index                 only regenerate src/data/dataFiles.generated.js (after adding a race by hand)
 *   node scripts/data/build.mjs check                 assemble the files on disk and print a summary
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitBundle, assembleBundle } from '../../src/data/dataLayout.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const dataDir = path.join(root, 'src/data');
const LAYOUT_DIRS = ['races', 'bases', 'shared'];

/** 2-space JSON, but arrays of plain numbers stay on one line (meshes would otherwise be 10x bigger on disk). */
const formatJson = (json) => JSON.stringify(json, null, 2).replace(/\[\s*(-?[\d.eE+-]+(?:,\s*-?[\d.eE+-]+)*)\s*\]/g, (m, inner) => `[${inner.replace(/\s+/g, '')}]`) + '\n';
const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8'));
const walk = (dir, base = dir) => fs.existsSync(dir)
  ? fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(dir, e.name), base) : [path.relative(base, path.join(dir, e.name)).split(path.sep).join('/')]))
  : [];

export function readLayoutFromDisk(dir = dataDir) {
  const files = {};
  for (const d of LAYOUT_DIRS) for (const rel of walk(path.join(dir, d), dir)) if (rel.endsWith('.json')) files[rel] = read(path.join(dir, rel));
  return files;
}

function writeIndex(files) {
  const paths = Object.keys(files).sort();
  const lines = ['// GENERATED by scripts/data/build.mjs - do not edit. Static imports so Vite and node load the same files.'];
  paths.forEach((p, i) => lines.push(`import f${i} from './${p}';`));
  lines.push('', 'export const DATA_FILES = {');
  paths.forEach((p, i) => lines.push(`  '${p}': f${i},`));
  lines.push('};', '');
  fs.writeFileSync(path.join(dataDir, 'dataFiles.generated.js'), lines.join('\n'));
}

function readMonolith(dir) {
  return {
    unitsVisuals: read(path.join(dir, 'visuals/units.json')),
    unitStats: read(path.join(dir, 'unitStats.json')),
    buildings: read(path.join(dir, 'buildings.json')),
    buildingVisuals: read(path.join(dir, 'buildingVisuals.json')),
    heroes: read(path.join(dir, 'heroes.json')),
    engineConfig: read(path.join(dir, 'engineConfig.json'))
  };
}

const cmd = process.argv[2] || 'check';
if (cmd === 'split') {
  const from = path.resolve(process.argv[3] || dataDir);
  if (!fs.existsSync(path.join(from, 'visuals/units.json'))) {
    console.error(`No monolithic units.json in ${from}.\nPut the exported files there (visuals/units.json, unitStats.json, buildings.json, buildingVisuals.json, heroes.json, engineConfig.json) and pass that folder:\n  node scripts/data/build.mjs split <folder>`);
    process.exit(1);
  }
  const files = splitBundle(readMonolith(from));
  for (const d of LAYOUT_DIRS) fs.rmSync(path.join(dataDir, d), { recursive: true, force: true });
  for (const [rel, json] of Object.entries(files)) {
    const out = path.join(dataDir, rel);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, formatJson(json));
  }
  writeIndex(files);
  console.log(`split -> ${Object.keys(files).length} files under src/data/{races,bases,shared}`);
} else if (cmd === 'index') {
  writeIndex(readLayoutFromDisk());
  console.log('index regenerated');
} else if (cmd === 'check') {
  const b = assembleBundle(readLayoutFromDisk());
  console.log('units:', Object.keys(b.unitsVisuals.units).length, 'prefabs:', Object.keys(b.unitsVisuals.prefabs).length,
    'stats:', Object.keys(b.unitStats.units).length, 'buildings:', Object.keys(b.buildings.buildings).length, 'heroes:', Object.keys(b.heroes.heroes).length);
} else {
  console.error('unknown command', cmd); process.exit(1);
}
